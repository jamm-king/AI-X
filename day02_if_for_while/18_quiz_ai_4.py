"""
고급 퀴즈: 물류창고 재고 및 주문 처리 시스템 (while + for + if 복합 제어)
실제 이커머스에서 사용하는 주문 접수 및 재고 차감 로직을 시뮬레이션하는 프로그램입니다.
초기 데이터:현재 창고의 상품 재고: inventory = 15
대기 중인 고객들의 주문 수량 리스트: orders = [3, 8, -2, 0, 5, 4, 1]
요구사항:for문을 사용하여 orders 리스트에 있는 주문을 순서대로 하나씩 처리합니다.
각 주문을 처리할 때 아래의 3가지 예외 조건을 if문으로 먼저 걸러내야 합니다.
주문 수량이 0 이하인 경우 (잘못된 주문): "잘못된 주문 수량(OO)입니다. 건너뜁니다."를 출력하고, 다음 주문으로 바로 넘어갑니다 (continue 사용).
남은 재고가 0인 경우 (품절 상태): "재고가 모두 소진되었습니다. 시스템을 종료합니다."를 출력하고 전체 반복을 즉시 중단합니다 (break 사용).
주문 수량이 남은 재고보다 많은 경우 (재고 부족): "재고가 부족하여 OO개 주문을 처리할 수 없습니다. (남은 재고: OO개)"를 출력하고, 해당 주문은 건너뜁니다.
위 예외에 걸리지 않는 정상 주문은 재고를 차감한 후, "OO개 주문 성공! (남은 재고: OO개)"를 출력합니다.
모든 주문 리스트를 다 돌았거나(반복문 정상 종료), 중간에 품절로 인해 종료(break)되었을 때 최종 결과를 출력합니다.
출력 형태: "--- 처리 완료 --- 최종 남은 재고: OO개, 처리된 총 주문 건수: OO건"
"""

inventory = 15
orders = [3, 8, -2, 0, 5, 4, 1]
cnt = 0

for order in orders:
    if inventory == 0:
        print("재고가 모두 소진되었습니다. 시스템을 종료합니다.")
        break
    if order <= 0:
        print(f"잘못된 주문 수량({order:0>2})입니다. 건너뜁니다.")
        continue
    if order > inventory:
        print(f"재고가 부족하여 {order:0>2}개 주문을 처리할 수 없습니다. (남은 재고: {inventory:0>2}개)")
        continue
        
    inventory -= order
    cnt += 1
    print(f"{order:0>2}개 주문 성공! (남은 재고: {inventory:0>2}개)")
    
print(f"--- 처리 완료 --- 최종 남은 재고: {inventory:0>2}개, 처리된 총 주문 건수: {cnt:0>2}건")